#ifndef PLATFORM_NATIVE_TOPOLOGY_ASSET_LAYOUT_H
#define PLATFORM_NATIVE_TOPOLOGY_ASSET_LAYOUT_H

/* Pointer-free byte-layout facts used by the offline topology asset census.
 * They are deliberately separate from native aggregate declarations: the
 * census reads little-endian byte spans and never casts retail asset bytes. */
#define NATIVE_TOPOLOGY_ASSET_RAW_SECTOR_BYTES 2352u
#define NATIVE_TOPOLOGY_ASSET_RAW_USER_OFFSET 24u
#define NATIVE_TOPOLOGY_ASSET_DATA_SECTOR_BYTES 2048u
#define NATIVE_TOPOLOGY_ASSET_PVD_LBA 16u
#define NATIVE_TOPOLOGY_ASSET_BIG_HEADER_BYTES 8u
#define NATIVE_TOPOLOGY_ASSET_BIG_ENTRY_BYTES 8u
#define NATIVE_TOPOLOGY_ASSET_BIG_HEADER_READ_CAP 0x4000u
#define NATIVE_TOPOLOGY_ASSET_DRAM_MAP_HEADER_BYTES 4u
#define NATIVE_TOPOLOGY_ASSET_NAV_HEADER_BYTES 0x4cu
#define NATIVE_TOPOLOGY_ASSET_NAV_FRAME_BYTES 0x14u
#define NATIVE_TOPOLOGY_ASSET_CHECKPOINT_BYTES 0x0cu

#define NATIVE_TOPOLOGY_ASSET_LEVEL_MESH_OFFSET 0x000u
#define NATIVE_TOPOLOGY_ASSET_LEVEL_RESTART_COUNT_OFFSET 0x148u
#define NATIVE_TOPOLOGY_ASSET_LEVEL_RESTART_POINTER_OFFSET 0x14cu
#define NATIVE_TOPOLOGY_ASSET_LEVEL_NAV_TABLE_OFFSET 0x188u
#define NATIVE_TOPOLOGY_ASSET_MESH_QUAD_COUNT_OFFSET 0x00u
#define NATIVE_TOPOLOGY_ASSET_MESH_QUAD_POINTER_OFFSET 0x0cu
#define NATIVE_TOPOLOGY_ASSET_QUAD_BYTES 0x5cu
#define NATIVE_TOPOLOGY_ASSET_QUAD_CHECKPOINT_OFFSET 0x3eu

#define NATIVE_TOPOLOGY_ASSET_RACE_COUNT 18u
#define NATIVE_TOPOLOGY_ASSET_BATTLE_COUNT 7u
#define NATIVE_TOPOLOGY_ASSET_CORPUS_COUNT (NATIVE_TOPOLOGY_ASSET_RACE_COUNT + NATIVE_TOPOLOGY_ASSET_BATTLE_COUNT)
#define NATIVE_TOPOLOGY_ASSET_STORED_FILES_PER_LEVEL 8u
#define NATIVE_TOPOLOGY_ASSET_LOD1_SELECTOR_OFFSET 0u
#define NATIVE_TOPOLOGY_ASSET_LOD1_ENVELOPE_SELECTOR_OFFSET 1u
#define NATIVE_TOPOLOGY_ASSET_LOD2_VRAM_SELECTOR_OFFSET 2u

#endif
